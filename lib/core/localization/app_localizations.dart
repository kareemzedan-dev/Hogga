  String translate(String key, {Map<String, String>? namedArgs}) {
    final raw = _localizedValues[locale.languageCode]?[key];
    String translation;
    if (raw != null) {
      translation = raw;
    } else {
      // Fallback: convert camelCase key to readable words
      // e.g. "cancelOrder" → "Cancel Order"
      translation = key
          .replaceAllMapped(
            RegExp(r'([A-Z])'),
            (m) => ' ${m.group(0)}',
          )
          .trim();
      if (translation.isNotEmpty) {
        translation =
            translation[0].toUpperCase() + translation.substring(1);
      }
    }
    if (namedArgs != null) {
      namedArgs.forEach((k, v) {
        translation = translation.replaceAll('{$k}', v);
      });
    }
    return translation;
  }
